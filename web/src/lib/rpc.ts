/** Read-only chain access. Used as the fallback when the indexer is missing or behind. */
import { createPublicClient, hexToString, http } from "viem";
import { monadTestnet } from "viem/chains";
import { pairwiseAbi } from "./abi";
import { CHAIN_READY, CONTRACT, RPC_URL } from "./env";
import type { Duel, Outcome, Side } from "./types";

export const publicClient = createPublicClient({
  chain: monadTestnet,
  transport: http(RPC_URL),
});

const OUTCOMES: readonly Outcome[] = ["OPEN", "A", "B", "REFUND"];
const SIDES: readonly (Side | null)[] = [null, "A", "B"];

export const outcomeFromNumber = (n: number): Outcome => OUTCOMES[n] ?? "OPEN";
export const sideFromNumber = (n: number): Side | null => SIDES[n] ?? null;

/** bytes32 room back to its slug, dropping the zero padding. */
export const decodeRoom = (room: `0x${string}`): string => hexToString(room, { size: 32 }).replace(/\0+$/, "");

function requireContract(): `0x${string}` {
  if (!CHAIN_READY) throw new Error("No contract configured. Set VITE_CONTRACT.");
  return CONTRACT as `0x${string}`;
}

export async function readDuel(id: string): Promise<Duel | null> {
  const raw = await publicClient.readContract({
    address: requireContract(),
    abi: pairwiseAbi,
    functionName: "getDuel",
    args: [BigInt(id)],
  });
  if (raw.creator === "0x0000000000000000000000000000000000000000") return null;
  return {
    id,
    creator: raw.creator.toLowerCase(),
    room: decodeRoom(raw.room),
    title: raw.title,
    uriA: raw.uriA,
    uriB: raw.uriB,
    hashA: raw.hashA,
    hashB: raw.hashB,
    createdAt: Number(raw.createdAt),
    commitEnd: Number(raw.commitEnd),
    revealEnd: Number(raw.revealEnd),
    poolA: raw.poolA,
    poolB: raw.poolB,
    // The chain does not track distinct participant counts; the indexer does.
    predictors: 0,
    committedVotes: 0,
    votesA: Number(raw.votesA),
    votesB: Number(raw.votesB),
    outcome: outcomeFromNumber(Number(raw.outcome)),
  };
}

export async function readDuelCount(): Promise<number> {
  const count = await publicClient.readContract({
    address: requireContract(),
    abi: pairwiseAbi,
    functionName: "duelCount",
  });
  return Number(count);
}

export async function readTasteRep(user: `0x${string}`): Promise<number> {
  const rep = await publicClient.readContract({
    address: requireContract(),
    abi: pairwiseAbi,
    functionName: "tasteRep",
    args: [user],
  });
  return Number(rep);
}

/** The stored vote commitment for one voter, or null when nothing is committed or readable. */
export async function readCommitment(id: string, user: `0x${string}`): Promise<`0x${string}` | null> {
  try {
    const ballot = await publicClient.readContract({
      address: requireContract(),
      abi: pairwiseAbi,
      functionName: "ballots",
      args: [BigInt(id), user],
    });
    return ballot[0];
  } catch {
    return null;
  }
}

/**
 * Onchain position and ballot for one user. The struct getters are generated by Solidity, so the
 * shape is only as reliable as Branch A's ABI: callers treat a failure as "unknown".
 */
export async function readMyState(
  id: string,
  user: `0x${string}`,
): Promise<{ side: Side | null; stake: bigint; firstAt: number; claimed: boolean; committed: boolean; revealed: Side | null; voterRewardClaimed: boolean } | null> {
  try {
    const address = requireContract();
    const [position, ballot] = await Promise.all([
      publicClient.readContract({ address, abi: pairwiseAbi, functionName: "positions", args: [BigInt(id), user] }),
      publicClient.readContract({ address, abi: pairwiseAbi, functionName: "ballots", args: [BigInt(id), user] }),
    ]);
    const [side, stake, firstAt, claimed] = position;
    const [commitment, revealed, rewardClaimed] = ballot;
    return {
      side: sideFromNumber(Number(side)),
      stake,
      firstAt: Number(firstAt),
      claimed,
      committed: commitment !== `0x${"0".repeat(64)}`,
      revealed: sideFromNumber(Number(revealed)),
      voterRewardClaimed: rewardClaimed,
    };
  } catch {
    return null;
  }
}
